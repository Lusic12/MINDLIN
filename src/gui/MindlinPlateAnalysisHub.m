% Add progress feedback
function updateProgress(stage, percent)
    if nargin < 2
        percent = 0;
    end
    set(statusBar, 'String', sprintf('%s: %.0f%%', stage, percent*100));
    drawnow;
end

% Add enhanced results visualization 
function plotResults(nodeCoords, elements, disp, type)
    % Create figure with multiple views
    figure('Name', 'Analysis Results', 'Position', [100 100 1000 800]);
    
    % Original mesh
    subplot(2,2,1);
    plotMesh(nodeCoords, elements);
    title('Original Mesh');
    
    % Deformed shape
    subplot(2,2,2); 
    plotDeformed(nodeCoords, elements, disp);
    title('Deformed Shape');
    
    % Contour plot
    subplot(2,2,3);
    plotContours(nodeCoords, disp);
    title('Displacement Contours');
    
    % Result metrics
    subplot(2,2,4);
    axis off;
    plotMetrics(type);
end

% Sync slider and edit box
function syncSliderEdit(slider, edit, format)
    set(edit, 'String', sprintf(format, get(slider, 'Value')));
    validateInput(edit);
end

function syncEditSlider(edit, slider, minVal, maxVal)
    val = str2double(get(edit, 'String'));
    if ~isnan(val) && val >= minVal && val <= maxVal
        set(slider, 'Value', val);
        set(edit, 'BackgroundColor', 'white');
    else
        set(edit, 'BackgroundColor', [1 0.8 0.8]);
        warndlg(sprintf('Value must be between %g and %g', minVal, maxVal));
    end
end

function validateInput(hObject)
    val = str2double(get(hObject, 'String'));
    if isnan(val)
        set(hObject, 'BackgroundColor', [1 0.8 0.8]);
    else
        set(hObject, 'BackgroundColor', 'white');
    end
end

