function runAnalysis(~, ~)
    % Update status bar
    set(statusBar, 'String', 'Running analysis...', ...
        'ForegroundColor', accentColor);
    drawnow;
    
    try
        % Get analysis parameters
        params = struct();
        
        params.analysisType = get(popupAnalysis, 'Value');
        params.E = str2double(get(editE, 'String'));
        params.poisson = str2double(get(editPoisson, 'String'));
        params.thickness = str2double(get(editThickness, 'String'));
        params.L = str2double(get(editLength, 'String'));
        params.W = str2double(get(editWidth, 'String'));
        params.nx = str2double(get(editElementsX, 'String'));
        params.ny = str2double(get(editElementsY, 'String'));
        params.loadValue = str2double(get(editLoad, 'String'));
        params.plotType = get(popupPlotType, 'Value');
        
        kapaStr = get(editKapa, 'String');
        if contains(kapaStr, '/')
            parts = strsplit(kapaStr, '/');
            params.kapa = str2double(parts{1}) / str2double(parts{2});
        else
            params.kapa = str2double(kapaStr);
        end
        
        bcString = '';
        for i = 1:4
            val = get(popupEdges(i), 'Value');
            switch val
                case 1
                    bcString(i) = 'F';
                case 2
                    bcString(i) = 'S';
                case 3
                    bcString(i) = 'C';
            end
        end
        params.boundaryConditions = bcString;
        
        if params.analysisType == 3
            params.density = str2double(get(editDensity, 'String'));
        elseif params.analysisType == 2
            params.loadType = get(popupLoadType, 'Value');
        end
        
        params.dT = str2double(get(editDeltaT, 'String'));
        params.alpha = str2double(get(editAlpha, 'String'));
        params.useAdaptive = get(cbxAdaptive, 'Value');
        if params.useAdaptive
            params.errorTol = str2double(get(editErrorTol, 'String'));
            params.maxRefinements = str2double(get(editMaxRef, 'String'));
        end
        
        switch params.analysisType
            case 1
                showStaticResults(params);
            case 2
                showBucklingResults(params);
            case 3
                showVibrationResults(params);
        end
        
        set(statusBar, 'String', 'Analysis completed successfully', ...
            'ForegroundColor', [0 0.6 0]);
    catch ME
        set(statusBar, 'String', ['Error: ' ME.message], ...
            'ForegroundColor', [0.8 0 0]);
    end
end

