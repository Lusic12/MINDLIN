    'String', {'All Results', 'Mesh Only', 'Deformation', 'Contour Plot'}, ...
    'Position', [130, 20, 150, 25]);

% Control Panel
panelControl = uipanel(figControl, 'Title', 'Analysis Control', ...
    'Position', [0.05, 0.02, 0.9, 0.07], ...
    'BackgroundColor', [0.94 0.94 0.94]);

