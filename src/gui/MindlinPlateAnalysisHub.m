function showMeshQuality(nodes, elements)
    nElements = size(elements, 1);
    aspectRatio = zeros(nElements, 1);
    skewness = zeros(nElements, 1);
    
    for el = 1:nElements
        nodeIds = elements(el, 2:5);
        xe = nodes(nodeIds, 2);
        ye = nodes(nodeIds, 3);
        
        dx = max(xe) - min(xe);
        dy = max(ye) - min(ye);
        aspectRatio(el) = max(dx/dy, dy/dx);
        
        angles = calculateElementAngles(xe, ye);
        skewness(el) = max(abs(angles - 90)) / 90;
    end
    
    figure('Name', 'Mesh Quality Assessment', ...
           'NumberTitle', 'off', ...
           'Position', [850, 400, 800, 400]);
    
    subplot(1,2,1);
    histogram(aspectRatio);
    title('Element Aspect Ratio');
    xlabel('Aspect Ratio');
    ylabel('Number of Elements');
    
    subplot(1,2,2);
    histogram(skewness);
    title('Element Skewness');
    xlabel('Skewness');
    ylabel('Number of Elements');
    
    fprintf('Mesh Quality Metrics:\n');
    fprintf('Aspect Ratio - Min: %.2f, Max: %.2f, Mean: %.2f\n', ...
            min(aspectRatio), max(aspectRatio), mean(aspectRatio));
    fprintf('Skewness    - Min: %.2f, Max: %.2f, Mean: %.2f\n', ...
            min(skewness), max(skewness), mean(skewness));
end

function angles = calculateElementAngles(xe, ye)
    angles = zeros(4,1);
    for i = 1:4
        j = mod(i, 4) + 1;
        k = mod(i-2, 4) + 1;
        v1 = [xe(j)-xe(i), ye(j)-ye(i)];
        v2 = [xe(k)-xe(i), ye(k)-ye(i)];
        
        cos_theta = dot(v1,v2)/(norm(v1)*norm(v2));
        angles(i) = acosd(cos_theta);
    end
end

