% Enhanced validation functions
function validateNumericInput(src, ~)
    val = str2double(get(src, 'String'));
    if isnan(val) || ~isreal(val)
        set(statusBar, 'String', 'Error: Please enter a valid number', ...
            'ForegroundColor', [0.8 0 0]);
        set(src, 'String', '0', 'BackgroundColor', [1 0.9 0.9]);
        return;
    end
    set(src, 'BackgroundColor', 'white');
    set(statusBar, 'String', 'Input validated', ...
        'ForegroundColor', [0.4 0.4 0.4]);
end

function validateIntegerInput(src, ~)
    val = str2double(get(src, 'String'));
    if isnan(val) || ~isreal(val) || val <= 0 || mod(val, 1) ~= 0
        set(statusBar, 'String', 'Error: Please enter a positive integer', ...
            'ForegroundColor', [0.8 0 0]);
        set(src, 'String', '1', 'BackgroundColor', [1 0.9 0.9]);
        return;
    end
    set(src, 'BackgroundColor', 'white');
    set(statusBar, 'String', 'Input validated', ...
        'ForegroundColor', [0.4 0.4 0.4]);
end

function validateFractionInput(src, ~)
    str = get(src, 'String');
    if contains(str, '/')
        parts = strsplit(str, '/');
        if length(parts) == 2
            num = str2double(parts{1});
            den = str2double(parts{2});
            if isnan(num) || isnan(den) || den == 0
                set(statusBar, 'String', 'Error: Please enter a valid fraction (e.g., 5/6)', ...
                    'ForegroundColor', [0.8 0 0]);
                set(src, 'String', '5/6', 'BackgroundColor', [1 0.9 0.9]);
                return;
            end
        else
            set(statusBar, 'String', 'Error: Please enter a valid fraction (e.g., 5/6)', ...
                'ForegroundColor', [0.8 0 0]);
            set(src, 'String', '5/6', 'BackgroundColor', [1 0.9 0.9]);
            return;
        end
    else
        val = str2double(str);
        if isnan(val) || ~isreal(val) || val <= 0
            set(statusBar, 'String', 'Error: Please enter a valid positive number or fraction', ...
                'ForegroundColor', [0.8 0 0]);
            set(src, 'String', '5/6', 'BackgroundColor', [1 0.9 0.9]);
            return;
        end
    end
    set(src, 'BackgroundColor', 'white');
    set(statusBar, 'String', 'Input validated', ...
        'ForegroundColor', [0.4 0.4 0.4]);
end

