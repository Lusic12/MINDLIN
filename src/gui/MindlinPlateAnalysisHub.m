function previewMesh(~, ~)
    try
        nx = str2double(get(editElementsX, 'String'));
        ny = str2double(get(editElementsY, 'String'));
        L = str2double(get(editLength, 'String'));
        W = str2double(get(editWidth, 'String'));
        
        [nodes, elements] = generateMesh(L, W, nx, ny);
        
        % Create preview figure
        previewFig = figure('Name', 'Mesh Preview', ...
            'NumberTitle', 'off', ...
            'Position', [850, 400, 500, 400]);
        
        % Plot mesh
        plotMesh(nodes, elements);
        title('Mesh Preview');
        axis equal tight;
        grid on;
        
        set(statusBar, 'String', 'Mesh preview generated', ...
            'ForegroundColor', [0 0.6 0]);
    catch ME
        set(statusBar, 'String', ['Mesh preview error: ' ME.message], ...
            'ForegroundColor', [0.8 0 0]);
    end
end

function plotMesh(nodes, elements)
    hold on;
    % Plot elements
    for el = 1:size(elements, 1)
        nodeIds = elements(el, 2:5);
        xe = nodes(nodeIds, 2);
        ye = nodes(nodeIds, 3);
        
        % Plot element edges
        plot([xe; xe(1)], [ye; ye(1)], 'b-', 'LineWidth', 0.5);
    end
    
    % Plot nodes
    plot(nodes(:,2), nodes(:,3), 'r.', 'MarkerSize', 8);
    
    xlabel('X (m)');
    ylabel('Y (m)');
    grid on;
    axis equal;
end

function showStaticResults(params)
    % Create new figure window for static analysis results
    figResults = figure('Name', 'Static Analysis Results', ...
        'NumberTitle', 'off', ...
        'Position', [850, 100, 900, 600]);
    
    % Run analysis
    [nodes, elements] = generateMesh(params.L, params.W, params.nx, params.ny);
    [K, F] = assembleSystem(nodes, elements, params.E, params.poisson, ...
        params.thickness, params.loadValue);
    [K_mod, F_mod] = applyBoundaryConditions(K, F, nodes, params.boundaryConditions);
    U = K_mod\F_mod;
    
    % Use enhanced plotting
    plotResults(nodes, elements, U, 1, params.plotType, ...
        get(popupColormap, 'String'){get(popupColormap, 'Value')}, ...
        get(cbxAnimate, 'Value'));
end

function showBucklingResults(params)
    % Create new figure window for buckling analysis results
    figResults = figure('Name', 'Buckling Analysis Results', ...
        'NumberTitle', 'off', ...
        'Position', [850, 100, 900, 600]);
    
    % Run buckling analysis
    [nodes, elements] = generateMesh(params.L, params.W, params.nx, params.ny);
    [K, ~] = assembleSystem(nodes, elements, params.E, params.poisson, ...
        params.thickness, 0);
    Kg = assembleGeometricStiffness(nodes, elements, params.loadValue);
    [K_mod, Kg_mod] = applyBucklingBoundaryConditions(K, Kg, nodes, params.boundaryConditions);
    [V, D] = eigs(K_mod, Kg_mod, 5, 'smallestabs');
    
    % Use enhanced plotting
    plotResults(nodes, elements, V(:,1), 2, params.plotType, ...
        get(popupColormap, 'String'){get(popupColormap, 'Value')}, ...
        get(cbxAnimate, 'Value'));
    
    % Display critical load factors in status bar
    criticalLoads = sort(diag(D), 'ascend');
    set(statusBar, 'String', sprintf('Critical load factors: %.4f, %.4f, %.4f', ...
        criticalLoads(1:3)), 'ForegroundColor', [0 0.6 0]);
end

function showVibrationResults(params)
    % Create new figure window for vibration analysis results
    figResults = figure('Name', 'Vibration Analysis Results', ...
        'NumberTitle', 'off', ...
        'Position', [850, 100, 900, 600]);
    
    % Run vibration analysis
    [nodes, elements] = generateMesh(params.L, params.W, params.nx, params.ny);
    [K, ~] = assembleSystem(nodes, elements, params.E, params.poisson, ...
        params.thickness, 0);
    M = assembleMassMatrix(nodes, elements, params.density, params.thickness);
    [K_mod, M_mod] = applyVibrationBoundaryConditions(K, M, nodes, params.boundaryConditions);
    [V, D] = eigs(K_mod, M_mod, 5, 'smallestabs');
    frequencies = sqrt(diag(D))/(2*pi);
    
    % Use enhanced plotting
    plotResults(nodes, elements, V(:,1), 3, params.plotType, ...
        get(popupColormap, 'String'){get(popupColormap, 'Value')}, ...
        get(cbxAnimate, 'Value'));
    
    % Display natural frequencies in status bar
    set(statusBar, 'String', sprintf('Natural frequencies (Hz): %.2f, %.2f, %.2f', ...
        frequencies(1:3)), 'ForegroundColor', [0 0.6 0]);
end

function updateAnalysisType(~, ~)
    analysisType = get(popupAnalysis, 'Value');
    
    % Enable/disable animation for dynamic analyses
    if analysisType > 1
        set(cbxAnimate, 'Enable', 'on');
    else
        set(cbxAnimate, 'Enable', 'off', 'Value', 0);
    end
    
    % Update status bar with analysis-specific instructions
    switch analysisType
        case 1
            set(statusBar, 'String', 'Static Analysis: Enter load and boundary conditions');
        case 2
            set(statusBar, 'String', 'Buckling Analysis: Select load type and boundary conditions');
        case 3
            set(statusBar, 'String', 'Vibration Analysis: Enter material density and boundary conditions');
    end
end

function runAnalysis(~, ~)
    % Update status bar
    set(statusBar, 'String', 'Running analysis...', ...
        'ForegroundColor', accentColor);
    drawnow;
    
    try
        % Get analysis parameters
        params = struct();
        
        params.analysisType = get(popupAnalysis, 'Value');
        params.E = str2double(get(editE, 'String'));
        params.poisson = str2double(get(editPoisson, 'String'));
        params.thickness = str2double(get(editThickness, 'String'));
        params.L = str2double(get(editLength, 'String'));
        params.W = str2double(get(editWidth, 'String'));
        params.nx = str2double(get(editElementsX, 'String'));
        params.ny = str2double(get(editElementsY, 'String'));
        params.loadValue = str2double(get(editLoad, 'String'));
        params.plotType = get(popupPlotType, 'Value');
        
        kapaStr = get(editKapa, 'String');
        if contains(kapaStr, '/')
            parts = strsplit(kapaStr, '/');
            params.kapa = str2double(parts{1}) / str2double(parts{2});
        else
            params.kapa = str2double(kapaStr);
        end
        
        bcString = '';
        for i = 1:4
            val = get(popupEdges(i), 'Value');
            switch val
                case 1
                    bcString(i) = 'F';
                case 2
                    bcString(i) = 'S';
                case 3
                    bcString(i) = 'C';
            end
        end
        params.boundaryConditions = bcString;
        
        if params.analysisType == 3
            params.density = str2double(get(editDensity, 'String'));
        elseif params.analysisType == 2
            params.loadType = get(popupLoadType, 'Value');
        end
        
        params.dT = str2double(get(editDeltaT, 'String'));
        params.alpha = str2double(get(editAlpha, 'String'));
        params.useAdaptive = get(cbxAdaptive, 'Value');
        if params.useAdaptive
            params.errorTol = str2double(get(editErrorTol, 'String'));
            params.maxRefinements = str2double(get(editMaxRef, 'String'));
        end
        
        switch params.analysisType
            case 1
                showStaticResults(params);
            case 2
                showBucklingResults(params);
            case 3
                showVibrationResults(params);
        end
        
        set(statusBar, 'String', 'Analysis completed successfully', ...
            'ForegroundColor', [0 0.6 0]);
    catch ME
        set(statusBar, 'String', ['Error: ' ME.message], ...
            'ForegroundColor', [0.8 0 0]);
    end
end

