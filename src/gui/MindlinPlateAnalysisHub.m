    % Get the current figure with results
    figResults = findobj('Type', 'figure', 'Name', 'Static Analysis Results');
    if isempty(figResults)
        figResults = findobj('Type', 'figure', 'Name', 'Buckling Analysis Results');
    end
    if isempty(figResults)
        figResults = findobj('Type', 'figure', 'Name', 'Vibration Analysis Results');
    end
    if ~isempty(figResults)
        figure(figResults);
        params = getCurrentConfig();
        % Pass scaleFactor to plotting functions if possible
        try
            switch params.analysisType
                case 1
                    showStaticResults(params, scaleFactor);
                case 2
                    showBucklingResults(params, scaleFactor);
                case 3
                    showVibrationResults(params, scaleFactor);
            end
        catch ME
            set(statusBar, 'String', ['Plot update error: ' ME.message], ...
                'ForegroundColor', [0.8 0 0]);
        end
    end
end

